"""
Report generator for Web-Sentinel results.
Generates clean structured Markdown and JSON reports (stripping terminal ANSI colors).
"""

import os
import re
import json
from datetime import datetime

ANSI_CLEANER = re.compile(r'\x1b\[[0-9;]*m')

def strip_ansi(obj):
    """Recursively strip ANSI color codes from nested dicts, lists, and strings."""
    if isinstance(obj, str):
        return ANSI_CLEANER.sub('', obj)
    elif isinstance(obj, dict):
        return {strip_ansi(k): strip_ansi(v) for k, v in obj.items()}
    elif isinstance(obj, list):
        return [strip_ansi(elem) for elem in obj]
    return obj

class Reporter:
    def __init__(self, target: str):
        self.target = target
        self.timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        self.report_data = {
            "target": target,
            "scan_time": self.timestamp,
            "modules": {}
        }
        
    def add_result(self, module_name: str, data: dict):
        self.report_data["modules"][module_name] = strip_ansi(data)
        
    def save_json(self, output_dir="reports"):
        os.makedirs(output_dir, exist_ok=True)
        safe_name = self.target.replace("://", "_").replace("/", "_").replace(":", "_")
        filepath = os.path.join(output_dir, f"report_{safe_name}.json")
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(self.report_data, f, indent=2)
        return filepath
        
    def save_markdown(self, output_dir="reports"):
        os.makedirs(output_dir, exist_ok=True)
        safe_name = self.target.replace("://", "_").replace("/", "_").replace(":", "_")
        filepath = os.path.join(output_dir, f"report_{safe_name}.md")
        
        md_lines = [
            f"# Web-Sentinel Security Audit Report",
            f"- **Target:** `{self.target}`",
            f"- **Scan Date:** {self.timestamp}",
            f"- **Generated By:** Web-Sentinel CLI",
            "",
            "---",
            ""
        ]
        
        for mod_name, mod_data in self.report_data["modules"].items():
            md_lines.append(f"## {mod_name.upper()}")
            if isinstance(mod_data, dict):
                for k, v in mod_data.items():
                    if isinstance(v, list):
                        md_lines.append(f"### {k.title()}")
                        if v:
                            for item in v:
                                md_lines.append(f"- {item}")
                        else:
                            md_lines.append("_None detected._")
                    else:
                        md_lines.append(f"- **{k}:** {v}")
            md_lines.append("")
            
        with open(filepath, "w", encoding="utf-8") as f:
            f.write("\n".join(md_lines))
        return filepath
